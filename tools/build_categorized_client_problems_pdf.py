def convert_to_pdf(html_file: Path, output_pdf: Path):
    output_pdf.parent.mkdir(parents=True, exist_ok=True)
    PROFILE_DIR.mkdir(parents=True, exist_ok=True)

    edge_binary = r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"
    if not os.path.exists(edge_binary):
        raise FileNotFoundError(f"Edge binary not found at: {edge_binary}")

    cmd = [
        edge_binary,
        "--headless",
        f"--user-data-dir={PROFILE_DIR}",
        "--disable-gpu",
        "--run-all-compositor-stages-before-draw",
        "--no-pdf-header-footer",
        f"--print-to-pdf={output_pdf}",
        str(html_file),
    ]

    print("Running Edge Headless PDF exporter...")
    result = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if result.returncode != 0:
        print("Edge stderr:", result.stderr)
        raise RuntimeError(f"Edge export failed with return code {result.returncode}")

    if not output_pdf.exists():
        raise FileNotFoundError(f"PDF was not generated at: {output_pdf}")

    size_kb = output_pdf.stat().st_size / 1024
    print(f"Successfully generated PDF at: {output_pdf} ({size_kb:.1f} KB)")


